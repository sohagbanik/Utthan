/**
 * Helper to safely get translated string with English/Hindi fallback
 */
export function getUIText(category, key, langId = 'en') {
  const cat = UI_TRANSLATIONS[category];
  if (!cat) return "";
  const item = cat[key];
  if (!item) return "";
  return item[langId] || item.bn || item.hi || item.en || "";
}

